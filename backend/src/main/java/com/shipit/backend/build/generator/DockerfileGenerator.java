package com.shipit.backend.build.generator;

import com.shipit.backend.build.exception.BuildException;
import com.shipit.backend.build.logging.BuildLogBuffer;
import com.shipit.backend.build.logging.LogSource;
import com.shipit.backend.build.model.BuildPlan;
import com.shipit.backend.build.model.ProjectType;
import lombok.extern.slf4j.Slf4j;
import org.springframework.stereotype.Component;

import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

/**
 * Synthesizes minimal, hardened, multi-stage Dockerfiles for detected applications
 * that do not provide their own custom Dockerfile.
 */
@Slf4j
@Component
public class DockerfileGenerator {

    private static final String DEFAULT_MAVEN_BUILDER_IMAGE = "maven:3.9.9-eclipse-temurin-21-alpine";

    /**
     * Generates a Dockerfile if necessary, writing it into the application root directory.
     *
     * @param appRoot Application root directory inside the workspace.
     * @param buildPlan Discovered build coordinates and metadata.
     * @param logBuffer Buffer for recording generation events.
     * @return Path to the Dockerfile to be used for container image building.
     */
    public Path generateDockerfile(Path appRoot, BuildPlan buildPlan, BuildLogBuffer logBuffer) {
        if (appRoot == null || !Files.exists(appRoot)) {
            throw new IllegalArgumentException("Application root directory must exist: " + appRoot);
        }
        if (buildPlan == null) {
            throw new IllegalArgumentException("BuildPlan must not be null");
        }

        // Custom Dockerfile already provided
        if (buildPlan.isCustomDockerfile() || buildPlan.getProjectType() == ProjectType.DOCKERFILE_CUSTOM) {
            Path customPath = Path.of(buildPlan.getDockerfilePath());
            if (!Files.exists(customPath)) {
                throw new BuildException("Referenced custom Dockerfile not found at: " + customPath, "DOCKERFILE_NOT_FOUND");
            }
            log.info("Using repository's custom Dockerfile at: {}", customPath);
            if (logBuffer != null) {
                logBuffer.append(LogSource.SYSTEM, "Using repository's custom Dockerfile.");
            }
            return customPath;
        }

        // Generate for Maven Spring Boot
        if (buildPlan.getProjectType() == ProjectType.MAVEN_SPRING_BOOT) {
            String dockerfileContent = synthesizeMavenDockerfile(buildPlan);
            Path targetDockerfile = appRoot.resolve("Dockerfile.shipit");

            try {
                Files.writeString(targetDockerfile, dockerfileContent, StandardCharsets.UTF_8);
                log.info("Generated multi-stage Dockerfile for deployment {} at {}",
                        buildPlan.getDeploymentId(), targetDockerfile);
                if (logBuffer != null) {
                    logBuffer.append(LogSource.SYSTEM, "Generated multi-stage Dockerfile for Maven Spring Boot application.");
                }
                buildPlan.setDockerfilePath(targetDockerfile.toAbsolutePath().toString());
                return targetDockerfile;
            } catch (IOException e) {
                log.error("Failed to write generated Dockerfile at: {}", targetDockerfile, e);
                throw new BuildException("Failed to generate Dockerfile: " + e.getMessage(), "DOCKERFILE_GENERATION_FAILED");
            }
        }

        throw new BuildException("Cannot generate Dockerfile for project type: " + buildPlan.getProjectType(), "UNSUPPORTED_PROJECT_TYPE");
    }

    /**
     * Synthesizes a hardened multi-stage Dockerfile for Java / Spring Boot.
     */
    public String synthesizeMavenDockerfile(BuildPlan buildPlan) {
        String builderImage = DEFAULT_MAVEN_BUILDER_IMAGE;
        String runnerImage = (buildPlan.getJreImage() != null && !buildPlan.getJreImage().isBlank())
                ? buildPlan.getJreImage()
                : "eclipse-temurin:21-jre-alpine";

        String compileCommand = (buildPlan.getBuildCommand() != null && !buildPlan.getBuildCommand().isBlank())
                ? buildPlan.getBuildCommand()
                : "mvn clean package -DskipTests -B";

        int port = buildPlan.getPort() > 0 ? buildPlan.getPort() : 8080;

        return String.format("""
                # --- Multi-Stage Build generated by ShipIt Build Engine ---
                # Stage 1: Build stage
                FROM %s AS builder
                WORKDIR /build

                # Copy build descriptors first for dependency layer caching
                COPY pom.xml .
                COPY .mvn/ .mvn/
                COPY mvnw mvnw.cmd* ./

                # Pre-download dependencies (optional cache step)
                RUN mvn dependency:go-offline -B || true

                # Copy remaining application source code
                COPY . .

                # Compile and package the application
                RUN %s

                # Stage 2: Minimal hardened runtime stage
                FROM %s AS runner
                WORKDIR /app

                # Run as dedicated unprivileged user for security
                RUN addgroup -g 10001 -S shipitgroup && \\
                    adduser -u 10001 -S shipituser -G shipitgroup

                # Copy packaged jar artifact from builder stage
                COPY --from=builder /build/target/*.jar /app/app.jar

                # Enforce non-root ownership
                RUN chown -R shipituser:shipitgroup /app

                USER shipituser

                EXPOSE %d

                ENTRYPOINT ["java", "-jar", "/app/app.jar"]
                """,
                builderImage,
                compileCommand,
                runnerImage,
                port
        );
    }
}
